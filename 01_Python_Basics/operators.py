# Arithmetic Operators

a = 10
b = 3

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a ** b)

# Assignment Operators

x = 10

print("Initial value:", x)

x += 5
print("After += 5:", x)

x -= 3
print("After -= 3:", x)

x *= 2
print("After *= 2:", x)

x /= 4
print("After /= 4:", x)

x //= 2
print("After //= 2:", x)

x %= 3
print("After %= 3:", x)

x **= 2
print("After **= 2:", x)

# Comparison Operators

a = 10
b = 5

print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)
print("a >= b:", a >= b)
print("a <= b:", a <= b)

# Logical Operators

x = 10
y = 5

print("x > 5 and y > 2:", x > 5 and y > 2)
print("x > 15 and y > 2:", x > 15 and y > 2)

print("x > 15 or y > 2:", x > 15 or y > 2)
print("x < 5 or y < 2:", x < 5 or y < 2)

print("not x > 5:", not x > 5)
print("not x < 5:", not x < 5)