# Python Variables

# Creating variables
name = "Maham"
age = 24
height = 5.5
is_engineer = True

# Printing variables
print(name)
print(age)
print(height)
print(is_engineer)

# Multiple variables
first_name = "Maham"
last_name = "Yasir"

print(first_name, last_name)

# Assigning multiple variables together
x, y, z = 10, 20, 30

print(x)
print(y)
print(z)

# Assigning the same value to multiple variables
a = b = c = 100

print(a)
print(b)
print(c)

# Checking variable type
print(type(name))
print(type(age))
print(type(height))
print(type(is_engineer))